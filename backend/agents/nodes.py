def summarizer_node(state: AgentState):
    p_data = state.get("patient_data", {})
    m_data = state.get("medical_data", {})
    safe = state.get("safety_approval", True)
    
    status_icon = "✅ APPROVED" if safe else "🚨 FLAG: REVIEW REQUIRED"
    
    summary = f"""### CLINICAL SYNTHESIS REPORT
Generated by MedFlow GraphRAG & LLM Engine

**Patient Profile:** {p_data.get('name')} (DOB: {p_data.get('dob')})

**Patient History & Timeline (Live DB Pull)**
{p_data.get('sql_history') if p_data.get('sql_history') else "No patient records found in the database."}

**Cross-Referenced Guidelines (AI)**
{m_data.get('guidelines')}

**Automated Safety & Conflict Check**
Status: {status_icon}
{m_data.get('safety_msg')}

**AI Recommendation**
{"Proceed with standard clinical pathway." if safe else "Please review the flagged safety conflicts immediately and consider an alternative prescription pathway."}"""
    
    response_message = AIMessage(content=summary)
    return {"summary": summary, "messages": [response_message]}
